  /// The whole map as rows of characters.
  static List<String> grid() {
    final out = List<StringBuffer>.generate(rows, (_) => StringBuffer());
    for (var rr = 0; rr < 3; rr++) {
      for (var rc = 0; rc < 3; rc++) {
        final room = rooms[(rc, rr)]!.$2;
        for (var r = 0; r < roomRows; r++) {
          out[rr * roomRows + r].write(room[r]);
        }
      }
    }
    return [for (final b in out) b.toString()];
  }

  /// Tile ids: 1 rock (auto-tiled later), 6 ledge, 7 spikes, 0 air.
  static List<int> tiles() => [
        for (final row in grid())
          for (final ch in row.split('')) ch == '#' ? 1 : (ch == '=' ? 6 : (ch == '^' ? 7 : 0)),
      ];

  /// Every placed thing: (character, column, row) in map cells.
  static List<(String, int, int)> things() {
    final out = <(String, int, int)>[];
    final g = grid();
    for (var r = 0; r < g.length; r++) {
      for (var c = 0; c < g[r].length; c++) {
        final ch = g[r][c];
        if ('PSDHWhgcfBE'.contains(ch)) out.add((ch, c, r));
      }
    }
    return out;
  }
